"""Генерация советов по экономии через OpenAI API."""
from __future__ import annotations

import json
import logging

from openai import AsyncOpenAI

from utils.config import OPENAI_API_KEY, OPENAI_MODEL

logger = logging.getLogger(__name__)

client = AsyncOpenAI(api_key=OPENAI_API_KEY)

ADVICE_PROMPT = """Ты — дружелюбный финансовый помощник для обычных людей в России. Тебе дают список расходов пользователя за последний месяц. Твоя задача — дать 3–5 полезных и реалистичных советов по экономии.

ГЛАВНЫЕ ПРАВИЛА:

1. НИКОГДА не советуй экономить на:
   - Образовании (оплата вуза, курсы, репетиторы)
   - Здоровье (лекарства, врачи, анализы)
   - Аренде жилья / ипотеке
   - Коммунальных платежах (ЖКХ)
   - Транспорте до работы/учёбы
   Эти расходы — фиксированные и обязательные. Просто пропусти их.

2. Советуй экономить ТОЛЬКО на повторяющихся необязательных тратах:
   - Кофе на вынос (частые покупки)
   - Доставка еды (можно готовить дома)
   - Импульсивные покупки (сладости, снеки, мелочи)
   - Подписки (неиспользуемые сервисы)
   - Такси (можно на метро/автобусе)
   - Обеды в кафе (можно брать с собой)

3. Каждый совет ОБЯЗАН содержать:
   - Конкретную сумму, которую человек тратит
   - Конкретную сумму, которую можно сэкономить
   - Конкретное альтернативное действие

4. Тон: дружелюбный, без нравоучений, как друг подсказывает. Не «вы должны», а «попробуй», «можно».

5. Если данных мало (менее 5 чеков или менее 3 000 руб.) — напиши:
   "📊 Пока мало данных для точного анализа. Отсканируй ещё чеки, и я дам персональные советы!"
   И дай 1–2 общих совета.

ФОРМАТ ОТВЕТА (строго):
Каждый совет — отдельный абзац. Формат:

{эмодзи} {Описание привычки и сумма} → {Альтернатива и экономия}

ПРИМЕРЫ ХОРОШИХ СОВЕТОВ:

☕ Ты покупаешь кофе ~14 раз в месяц на 4 200 руб. → Термос с домашним кофе обойдётся в ~800 руб. Экономия: ~3 400 руб./мес.

🍕 Заказываешь доставку еды 8 раз на 6 400 руб. → Готовь 4 раза из 8 дома — сэкономишь ~3 200 руб./мес.

🍫 Сладости и снеки: 12 покупок на 2 100 руб. → Сократи до 6 покупок — минус ~1 050 руб./мес.

ПРИМЕРЫ ПЛОХИХ СОВЕТОВ (НИКОГДА так не пиши):
❌ "Оплата вуза стоит 113 500 руб. Поищи аналог дешевле" — бред, образование не меняют
❌ "Тратьте меньше на продукты" — слишком абстрактно, без цифр
❌ "Сократите расходы на лекарства" — опасный совет

ВАЖНО: Отвечай ТОЛЬКО советами. Без вступления «Вот мои советы:», без заключения. Сразу начинай с первого совета.

Расходы пользователя за последний месяц:
{expenses_json}"""

MINI_ADVICE_PROMPT = """Дай ОДИН короткий совет по экономии на основе этого чека.

Позиции чека:
{items_summary}

Правила:
- Только если есть явно необязательная трата (кофе, сладости, снеки, готовая еда, алкоголь)
- Если в чеке только базовые продукты/лекарства/необходимое — ответь: "none"
- Формат: одно предложение, дружелюбно, с конкретной суммой
- НИКОГДА не советуй экономить на лекарствах, образовании, ЖКХ

Пример: "☕ Кофе за 459 руб. — домашний обойдётся в ~30 руб. за чашку."
Пример: "none" (если в чеке только молоко, хлеб, яйца)"""


async def generate_advice(expenses_data: dict) -> str:
    """
    Сгенерировать персональные советы по экономии через OpenAI GPT.

    expenses_data — словарь из queries.get_expenses_for_advice().
    Возвращает готовый текст советов.
    """
    by_category = expenses_data.get("by_category", {})
    total_receipts = expenses_data.get("total_receipts", 0)
    days = expenses_data.get("days", 30)

    expenses_for_prompt = {
        "период_дней": days,
        "количество_чеков": total_receipts,
        "расходы_по_категориям": {
            cat: {
                "сумма_руб": round(data["total"], 2),
                "количество_покупок": data["count"],
            }
            for cat, data in by_category.items()
        },
    }

    expenses_json = json.dumps(expenses_for_prompt, ensure_ascii=False, indent=2)

    try:
        response = await client.chat.completions.create(
            model=OPENAI_MODEL,
            messages=[
                {
                    "role": "user",
                    "content": ADVICE_PROMPT.format(expenses_json=expenses_json),
                }
            ],
            max_tokens=1024,
        )

        advice_text = response.choices[0].message.content.strip()
        logger.info(
            f"Сгенерированы советы. Чеков: {total_receipts}, категорий: {len(by_category)}"
        )
        return advice_text

    except Exception as e:
        logger.error(f"Ошибка OpenAI API при генерации советов: {e}")
        return "😕 Не удалось получить советы. Попробуй позже."


async def generate_mini_advice(items: list) -> str:
    """
    Сгенерировать короткий мини-совет после скана чека.

    Возвращает одно предложение или пустую строку если совет неуместен.
    """
    if not items:
        return ""

    items_summary = "\n".join(
        f"- {item.get('name', '')} [{item.get('category', '')}]: {item.get('total', 0):.2f} руб."
        for item in items[:15]
    )

    try:
        response = await client.chat.completions.create(
            model=OPENAI_MODEL,
            messages=[
                {
                    "role": "user",
                    "content": MINI_ADVICE_PROMPT.format(items_summary=items_summary),
                }
            ],
            max_tokens=100,
            temperature=0.3,
        )
        result = response.choices[0].message.content.strip()

        # Если модель ответила "none" — не показываем совет
        if result.lower().startswith("none"):
            return ""
        return result

    except Exception as e:
        logger.error(f"Ошибка генерации мини-совета: {e}")
        return ""
